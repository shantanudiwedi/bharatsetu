export type TranslationKey = keyof typeof translations.en;

interface TranslationContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
}

const TranslationContext = createContext<TranslationContextValue | null>(null);

export function TranslationProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('bharatsetu-language');
    return saved === 'hi' || saved === 'mr' ? saved : 'en';
  });

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    localStorage.setItem('bharatsetu-language', next);
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key: TranslationKey) => translations[language][key],
  }), [language]);

  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
}

export function useTranslation() {
  const context = useContext(TranslationContext);
  if (!context) throw new Error('useTranslation must be used inside TranslationProvider');
  return context;
}

export function translateAuditSource(source: string, t: TranslationContextValue['t']) {
  if (source === 'Document Pipeline') return t('documentPipeline');
  if (source === 'AI Engine') return t('aiEngine');
  if (source === 'Verification Engine') return t('verificationEngine');
  if (source === 'Procurement Officer') return t('procurementOfficer');
  return source;
}

export function translateAuditAction(action: string, t: TranslationContextValue['t']) {
  const uploaded = action.match(/^Uploaded & classified document '([^']+)' as (.+)$/);
  if (uploaded) {
    return `${t('uploadedClassifiedDocument')} '${uploaded[1]}' (${t('classifiedAs')}: ${uploaded[2]})`;
  }

  const complete = action.match(/^Verification complete: Risk Score (.+) \((HIGH|MEDIUM|LOW)\), Compliance (.+)$/);
  if (complete) {
    const riskLabel = complete[2] === 'HIGH' ? t('highRisk') : complete[2] === 'MEDIUM' ? t('mediumRisk') : t('lowRisk');
    return `${t('verificationCompleteAction')}: ${t('riskScore')} ${complete[1]} (${riskLabel}), ${t('compliancePercentage')} ${complete[3]}`;
  }

  if (action === 'Started automated verification pipeline') return t('startedAutomatedPipeline');

  const completed = action.match(/^Verification completed for Bid (.+)\. Risk Level: (.+)$/);
  if (completed) {
    return `${t('verificationCompletedForBid')} ${completed[1]}. ${t('riskLevel')}: ${completed[2]}`;
  }

  return action;
}

